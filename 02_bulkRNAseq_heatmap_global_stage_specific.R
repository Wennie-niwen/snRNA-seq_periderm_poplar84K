# ============================================================
# Script: 02_bulkRNAseq_heatmap_global_stage_specific.R
# Description: TCseq clustering of genes shared between EI and SI that were upregulated at each of the three developmental stages
# Associated Figures: Figure 1D
# ============================================================

library(tidyverse)
library(data.table)
library(ComplexHeatmap)
library(circlize)
library(grid)
library(matrixStats)

data_dir  <- "data"
outdir    <- 'results'
outdir2   <- 'plots'

if(!dir.exists(outdir)) dir.create(outdir, recursive = TRUE)
if(!dir.exists(outdir2)) dir.create(outdir2, recursive = TRUE)

chosen <- "G8"

# ============ 1. Read final filtered genes and assignments ============
# Read the assignments generated by 01_bulk_analysis.R
final_gene_table <- fread(file.path(outdir, 'Final_Gene_Group_Assignment.txt'))
cat("Final gene distribution:\n")
print(table(final_gene_table$group))

# ============ 2. Read metadata and TPM matrices ============
# Read the metadata defined in the first script
# (Since it's not saved as a CSV, we recreate the minimal parts needed for plotting)
metadata <- data.frame(
  sample = c(
    "SI_S1_R1", "SI_S1_R2", "SI_S1_R3",
    "SI_S2_R1", "SI_S2_R2", "SI_S2_R3",
    "SI_S3a_R1", "SI_S3a_R2", "SI_S3a_R3",
    "SI_S3b_R1", "SI_S3b_R2", "SI_S3b_R3",
    "EI_S1_R1", "EI_S1_R2", "EI_S1_R3",
    "EI_S2_R1", "EI_S2_R2", "EI_S2_R3",
    "EI_S3_R1", "EI_S3_R2", "EI_S3_R3",
    "EI_S1_V_R1", "EI_S1_V_R2", "EI_S1_V_R3",
    "EI_S2_V_R1", "EI_S2_V_R2", "EI_S2_V_R3",
    "EI_S3_V_R1", "EI_S3_V_R2", "EI_S3_V_R3"
  ),
  group_2 = c(
    rep("Stage I", 3), rep("Stage II", 3), rep("Stage III", 6),
    rep("Stage I", 3), rep("Stage II", 3), rep("Stage III", 3),
    rep("Vascular", 9)
  ),
  stringsAsFactors = FALSE 
)

# Read TPM files from GEO (downloaded into data_dir)
TPM1 <- read.table(file.path(data_dir, "SI_TPM_matrix.txt"), header = T)
TPM2 <- read.table(file.path(data_dir, "EI_TPM_matrix.txt"), header = T)
TPM <- merge(TPM1, TPM2, by="gene") %>% column_to_rownames(var = "gene")

# Extract TPM values only for the final filtered genes
TPM_filtered <- TPM[final_gene_table$gene, ]

# ============ 3. Process SI Matrix ============
TPM_sample1 <- TPM_filtered[, 1:12]
meta_sample1 <- metadata[1:12, ]
meta_sample1$group_2 <- factor(meta_sample1$group_2, levels = c("Stage I", "Stage II", "Stage III"))
meta_sample_sorted1 <- meta_sample1[order(meta_sample1$group_2), ]

# Reorder columns and calculate Z-score
mat1 <- TPM_sample1[, meta_sample_sorted1$sample]
mat_z1 <- (mat1 - rowMeans(mat1)) / rowSds(as.matrix(mat1))
mat_z1 <- as.matrix(mat_z1)
mat_z1[is.na(mat_z1)] <- 0

# ============ 4. Process EI Matrix ============
TPM_sample2 <- TPM_filtered[, 13:30]
meta_sample2 <- metadata[13:30, ]
meta_sample2$group_2 <- factor(meta_sample2$group_2, levels = c("Vascular", "Stage I", "Stage II", "Stage III"))
meta_sample_sorted2 <- meta_sample2[order(meta_sample2$group_2), ]

# Reorder columns and calculate Z-score
mat2 <- TPM_sample2[, meta_sample_sorted2$sample]
mat_z2 <- (mat2 - rowMeans(mat2)) / rowSds(as.matrix(mat2))
mat_z2 <- as.matrix(mat_z2)
mat_z2[is.na(mat_z2)] <- 0

# ============ 5. Filter out Stable & Row ordering ============
# CRITICAL: Remove Stable genes to speed up plotting and focus on stages
plot_genes <- final_gene_table$gene[final_gene_table$group != "Stable"]

mat_z1 <- mat_z1[plot_genes, ]
mat_z2 <- mat_z2[plot_genes, ]

group_vec <- factor(final_gene_table$group[final_gene_table$group != "Stable"], 
                    levels = c("Stage I", "Stage II", "Stage III"))

# Sort by group
ord <- order(group_vec)
mat_z1 <- mat_z1[ord, ]
mat_z2 <- mat_z2[ord, ]
group_vec <- group_vec[ord]

cat("Total genes to plot (excluding Stable):", length(plot_genes), "\n")
print(table(group_vec))

# Colors
ht_colors <- colorRampPalette(c("#2166AC", "white", "#B2182B"))(100)
col_fun   <- colorRamp2(seq(-2, 2, length.out = 100), ht_colors)

group_colors <- c(
  "Vascular"  = "lightgrey",
  "Stage I"   = "#56B4E9",
  "Stage II"  = "#F79431",
  "Stage III" = "#D44637"
)

# Column annotations
col_group1 <- factor(meta_sample_sorted1$group_2, levels = c("Stage I", "Stage II", "Stage III"))
col_ha1 <- HeatmapAnnotation(
  Group = col_group1,
  col   = list(Group = group_colors[levels(col_group1)]),
  show_annotation_name = TRUE,
  annotation_name_gp   = gpar(fontsize = 10),
  show_legend          = TRUE
)

col_group2 <- factor(meta_sample_sorted2$group_2, levels = c("Vascular", "Stage I", "Stage II", "Stage III"))
col_ha2 <- HeatmapAnnotation(
  Group = col_group2,
  col   = list(Group = group_colors[levels(col_group2)]),
  show_annotation_name = TRUE,
  annotation_name_gp   = gpar(fontsize = 10),
  show_legend          = TRUE
)

# Row annotation
row_ha <- rowAnnotation(
  Cluster = group_vec,
  col     = list(Cluster = group_colors),
  show_annotation_name = FALSE,
  show_legend          = TRUE
)

# ============ 6. Draw Heatmaps (Optimized for speed) ============
ht1 <- Heatmap(
  mat_z1,
  name             = "Z-score (SI)",
  col              = col_fun,
  top_annotation   = col_ha1,
  row_split        = group_vec,
  cluster_row_slices = FALSE,
  cluster_rows     = FALSE, # Turn off row clustering to speed up
  show_row_dend    = FALSE,
  row_title_gp     = gpar(fontsize = 11, fontface = "bold"),
  column_split     = col_group1,
  cluster_columns  = FALSE,
  show_column_names = TRUE,
  column_names_rot = 90,
  column_names_gp  = gpar(fontsize = 8),
  column_names_centered = TRUE,
  column_gap       = unit(1.5, "mm"),
  show_row_names   = FALSE,
  use_raster       = TRUE,  # Keep rasterization ON for huge matrices
  raster_quality   = 1,     # LOWER quality for much faster rendering (sufficient for PDF)
  row_gap          = unit(2, "mm"),
  border           = TRUE
)

ht2 <- Heatmap(
  mat_z2,
  name             = "Z-score (EI)",
  col              = col_fun,
  left_annotation  = row_ha,
  top_annotation   = col_ha2,
  row_split        = group_vec,
  cluster_row_slices = FALSE,
  cluster_rows     = FALSE, # Turn off row clustering to speed up
  show_row_dend    = FALSE,
  row_title_gp     = gpar(fontsize = 11, fontface = "bold"),
  column_split     = col_group2,
  cluster_columns  = FALSE,
  show_column_names = TRUE,
  column_names_rot = 90,
  column_names_gp  = gpar(fontsize = 8),
  column_names_centered = TRUE,
  column_gap       = unit(1.5, "mm"),
  show_row_names   = FALSE,
  use_raster       = TRUE,  # Keep rasterization ON
  raster_quality   = 1,     # LOWER quality for much faster rendering
  row_gap          = unit(2, "mm"),
  border           = TRUE
)

# ============ 7. Combine and save ============
pdf(file.path(outdir2, paste0('Heatmap_cluster3_', chosen, '_SI_EI_final.pdf')),
    width = 5, height = 6)
draw(ht2 + ht1, merge_legend = TRUE)
dev.off()

cat("Heatmap saved successfully.\n")
